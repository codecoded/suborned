def glb(path):
    b = open(path, 'rb').read(); n = struct.unpack('<I', b[12:16])[0]; j = json.loads(b[20:20 + n]); off = 20 + n + 8; bin_ = b[off:]
    tris = 0
    for me in j.get('meshes', []):
        for pr in me['primitives']:
            if 'indices' in pr: tris += j['accessors'][pr['indices']]['count'] // 3
            else: tris += j['accessors'][pr['attributes']['POSITION']]['count'] // 3
    sizes = []
    for im in j.get('images', []):
        if 'bufferView' in im:
            bv = j['bufferViews'][im['bufferView']]; d = bin_[bv.get('byteOffset', 0):bv.get('byteOffset', 0) + bv['byteLength']]
            if d[:12] == b'\xabKTX 20\xbb\r\n\x1a\n': sizes.append(struct.unpack('<II', d[20:28]))
            else:
                try: sizes.append(Image.open(io.BytesIO(d)).size)
                except Exception: sizes.append(None)
    return tris, sizes
def resolve(s): return os.path.normpath(os.path.join(STORE, s))
