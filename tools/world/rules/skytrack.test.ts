// SK-T1..SK-T3, the old sky track (brief 075 roll-out, step 2; tools/world/gen/street/skytrack.ts). The live export passes; each failing example breaks one thing on a copy of it.
import { expect, setDefaultTimeout, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { Mass, World } from '../../../contracts/world/world.schema';
import { civic } from '../../plan/civic';
import type { V } from '../../plan/geom';
import { derive, type Plan } from '../../plan/plan';
import { ctxOf, generated } from '../../plan/world-ctx';
import { BEAM, PYLON } from '../gen/street/skytrack';
import { skyTrackRules } from './skytrack';
import { prePlan } from '../test/preremap';

setDefaultTimeout(180000);
const root = resolve(import.meta.dir, '../../..'), read = (p: string) => JSON.parse(readFileSync(resolve(root, p), 'utf8'));
// brief 075 remap: these examples and counts were written on the district plan before the old town replaced it; they run on that plan, pinned
// (briefs/075/remap/base.plan.json, committed), generated by today's code. The live plan's world is held by the world rules (bun run plan).
const plan: Plan = prePlan(), d = derive(plan), civ = civic(plan.civic, read(plan.civic.block)), base = generated(plan, d, civ);
const run = (w: World) => Object.fromEntries(skyTrackRules(ctxOf(plan, d, civ, { w, gen: base.gen })).map(c => [c.id, c]));
const clone = (w: World): World => structuredClone(w);
const st = base.w.transit.skyTrack!;

test('the live export: SK-T1..SK-T3 pass; a stack at every plan pylon, the twin head on the double trunk, the single on the loop; two trunk beams 6 m apart and the loop\'s one', () => {
  const r = run(base.w);
  for (const id of ['SK-T1', 'SK-T2', 'SK-T3']) expect(r[id]!.ok, `${id} ${r[id]!.detail}`).toBe(true);
  const plans = base.w.transit.skyRail.reduce((n, s) => n + s.pylons.length, 0);
  expect(st.pylons.length).toBe(plans);
  for (const p of st.pylons) expect(p.head.id).toBe(p.id.includes('/trunk/') ? PYLON.headTwin : PYLON.head);
  expect(st.pylons.filter(p => p.foot?.id === PYLON.tall).length).toBeGreaterThan(25); // the old 12 m plinth wherever it fits
  expect(st.beam.beams.map(b => b.id)).toEqual(['skyrail/S1/trunk/beam-0', 'skyrail/S1/trunk/beam-1', 'skyrail/S1/loop/beam-0']);
  const [b0, b1] = st.beam.beams;
  expect(Math.abs(b0!.line[10]![1] - b1!.line[10]![1])).toBeCloseTo(plan.standards.skyrail.beamCentres, 3);
  expect(st.beam.piece).toBe(BEAM.piece); expect([st.beam.width, st.beam.depth, st.beam.fillet]).toEqual([1.2, 1.6, 0.22]);
  // the export still carries the ribbons and posts for a builder that does not read skyTrack
  expect(base.w.transit.skyRail.every(s => s.line.length > 10 && s.pylons.length > 0)).toBe(true);
});

test('failing example (SK-T1): a head hung 1 m low, and a plan pylon with no stack', () => {
  const w = clone(base.w); w.transit.skyTrack!.pylons[3]!.head.z -= 1;
  expect(run(w)['SK-T1']!.ok).toBe(false); expect(run(w)['SK-T1']!.detail).toContain('is not the beam underside');
  const v = clone(base.w); v.transit.skyTrack!.pylons.splice(5, 1);
  expect(run(v)['SK-T1']!.detail).toContain('has no stack');
});

test('failing example (SK-T2): a lamp standing on a Tall plinth, and a plinth that leaves the pylon ground', () => {
  const w = clone(base.w), p = w.transit.skyTrack!.pylons.find(x => x.foot?.id === PYLON.tall)!, lamp = w.street.find(s => s.kind === 'lamp' && s.z < 1)!;
  lamp.at = [p.at[0] + 1.5, p.at[1]] as V;
  expect(run(w)['SK-T2']!.ok).toBe(false); expect(run(w)['SK-T2']!.detail).toContain(`stands on the lamp ${lamp.id}`);
  const v = clone(base.w), q = v.transit.skyTrack!.pylons.find(x => x.foot?.id === PYLON.tall && x.on.startsWith('median/'))!;
  q.at = [q.at[0], q.at[1] + 6] as V; // its plinth now straddles the median's edge and the carriageway (and the plan pylon has lost its stack)
  expect(run(v)['SK-T2']!.detail).toContain('leaves the pylon ground');
});

test('failing example (SK-T3): a building raised into the trunk beam', () => {
  const w = clone(base.w), b = w.transit.skyTrack!.beam.beams[0]!, at = b.line[40]!;
  const m: Mass = { id: 'bld/test/0/body', surface: 'stone', ring: [[at[0] - 3, at[1] - 3], [at[0] + 3, at[1] - 3], [at[0] + 3, at[1] + 3], [at[0] - 3, at[1] + 3]], base: 0, height: 30 };
  w.buildings.push(m);
  expect(run(w)['SK-T3']!.ok).toBe(false); expect(run(w)['SK-T3']!.detail).toContain('runs through bld/test/0/body');
  // the same mass kept under the beam's underside passes
  const v = clone(base.w); v.buildings.push({ ...m, height: b.top - BEAM.depth - 0.5 });
  expect(run(v)['SK-T3']!.ok).toBe(true);
});
