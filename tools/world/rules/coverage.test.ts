test('a crossroads or junction crossing missing fails; a foot site missing fails naming the group; a plot-edge crossing no rule keeps fails (edges is false)', () => {
  const cr = base.w.crossings!.find(c => c.road === 'market-street' && Math.abs(mid(c)[0] + 77) < 1)!; // Satellite Gate's crossroads, 17 m before the node
  const a = run(w => { w.crossings = w.crossings!.filter(c => c.id !== cr.id); })!;
  expect(a.ok).toBe(false); expect(a.detail).toMatch(/crossroads\/market-street\/g_satellite\/before \(.*\) has no crossing within 4 m and is not named as left out/);
  const parade = base.w.crossings!.find(c => c.landings.some(l => /^street\/foot\/crown-parade\//.test(l.id)))!;
  const b = run(w => { w.crossings = w.crossings!.filter(c => c.id !== parade.id); })!;
  expect(b.ok).toBe(false); expect(b.detail).toMatch(/foot\/crown-parade\/harbour-road \(.*\) has no crossing within 4 m of its axis or its walk bands and is not named as left out or served/);
  // a copy of a crossroads crossing moved 40 m along Market Street: a plot-edge crossing the rules do not keep
  const c = run(w => {
    const clone = structuredClone(w.crossings!.find(q => q.id === cr.id)!); clone.id = 'crossing/test/edge'; clone.line = [[clone.line[0][0] + 40, clone.line[0][1]], [clone.line[1][0] + 40, clone.line[1][1]]];
    clone.landings = clone.landings.map((l, i) => ({ ...l, id: `street/zz-edge/e0/crossing-${i}` })) as never; w.crossings!.push(clone);
  })!;
  expect(c.ok).toBe(false); expect(c.detail).toMatch(/crossing\/test\/edge is a plot-edge crossing and no rule keeps it \(rules\.edges is false\)/);
});

test('a bank patch, a second stop end or a stop at the far platform end fails', () => {
  const bank = run(w => { const x = structuredClone(w.crossings!.find(q => q.kind === 'stop')!); x.id = 'crossing/bank/test'; x.kind = 'bank'; w.crossings!.push(x); })!;
  expect(bank.ok).toBe(false); expect(bank.detail).toMatch(/crossing\/bank\/test is a station bank patch and the rules say banks false/);
  const two = run(w => { const x = structuredClone(w.crossings!.find(q => q.kind === 'stop')!); x.id = `${x.id}9`; w.crossings!.push(x); })!;
  expect(two.ok).toBe(false); expect(two.detail).toMatch(/has 2 crossings, the rules give a stop 1/);
});

test('a site the export names as left out passes, and fails when the log forgets it; a name no rule makes fails', () => {
  const site = 'crossroads/market-street/g_satellite/before', cr = base.w.crossings!.find(c => c.road === 'market-street' && Math.abs(mid(c)[0] + 77) < 1)!;
  const gone = (log: string[]) => run(w => { w.crossings = w.crossings!.filter(c => c.id !== cr.id); w.crossingRules!.left = log; })!;
  expect(gone([`${site}: no free spot for the landing at kerb a (nor within 4 m either way)`]).ok).toBe(true);
  const forgot = gone([]);
  expect(forgot.ok).toBe(false); expect(forgot.detail).toContain(`${site} `);
  const stray = run(w => { w.crossingRules!.left.push('arm/nowhere/x: no free spot'); })!;
  expect(stray.ok).toBe(false); expect(stray.detail).toContain("the export names 'arm/nowhere/x' as left out, and no rule makes that site");
  const strayServed = run(w => { w.crossingRules!.served = [...(w.crossingRules!.served ?? []), 'foot/nowhere/x: crossing-1']; })!;
  expect(strayServed.ok).toBe(false); expect(strayServed.detail).toContain("the export names 'foot/nowhere/x' as served, and no rule makes that site");
});

test('a twin across a side road\'s mouth fails: a copy of a kerb crossing put across a side road\'s mouth, 25 m from the one it copies', () => {
  const kerbs = kerb(base.w).filter(c => !isSite(c)).map(c => { const r = d.roads.find(q => q.id === c.road)!; return { c, r, node: r.path.map(n => plan.nodes[n]!).find(n => Math.hypot(n[0] - mid(c)[0], n[1] - mid(c)[1]) < 20 && d.roads.some(q => q !== r && q.path.some(m => plan.nodes[m] === n))) }; }).find(x => x.node && x.r.class !== 'primary')!;
  const m = mid(kerbs.c), n = kerbs.node!, dx = (n[0] - m[0]) * 1.5, dy = (n[1] - m[1]) * 1.5; // a crossing stands 17 m before its node: the copy 8 m past it
  const r = run(w => {
    const clone = structuredClone(w.crossings!.find(c => c.id === kerbs.c.id)!);
    clone.id = 'crossing/test/twin'; clone.line = [[clone.line[0][0] + dx, clone.line[0][1] + dy], [clone.line[1][0] + dx, clone.line[1][1] + dy]];
    clone.landings = clone.landings.map((l, i) => ({ ...l, id: `street/zz-twin/${i}` })) as never;
    w.crossings!.push(clone);
  })!;
  expect(r.ok).toBe(false);
  expect(r.detail).toMatch(/crossing\/test\/twin is a twin across a side road's mouth \(\d+ m from the crossing it keeps\)/);
});
