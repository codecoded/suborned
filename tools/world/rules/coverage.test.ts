// SF-22 and the crossing coverage rules (plan crossings.coverage.rules; Datum's rules of 2026-10-25 for brief 061, Sky: "way too many crossings"; written by Splice): a plot edge gives no crossing; the rules keep 26: a tram stop's one end, the circus island's
// one line per road, a footway's crossing of a road, the district roads' crossroads and junction arms, and the civic block's own. The generator keeps the plot-edge landing a rule's site coincides with (the furniture round the others stays where it was),
// places what no landing serves, and says so in the export's crossingRules; SF-22 holds the export to it. Each failing example puts one thing back.
import { expect, setDefaultTimeout, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { World } from '../../../contracts/world/world.schema';
import { civic, toPlanFn } from '../../plan/civic';
import { type V, dist } from '../../plan/geom';
import { derive, type Plan } from '../../plan/plan';
import { ctxOf, generated } from '../../plan/world-ctx';
import { kerbReturnStd } from '../gen/kerbreturn';
import { junctionPoints } from '../gen/street/siting';
import { extraRules } from './index';
import { prePlan } from '../test/preremap';

setDefaultTimeout(120000);
const root = resolve(import.meta.dir, '../../..'), read = (p: string) => JSON.parse(readFileSync(resolve(root, p), 'utf8'));
// brief 075 remap: these examples and counts were written on the district plan before the old town replaced it; they run on that plan, pinned
// (briefs/075/remap/base.plan.json, committed), generated by today's code. The live plan's world is held by the world rules (bun run plan).
const plan: Plan = prePlan(), d = derive(plan), civ = civic(plan.civic, read(plan.civic.block)), base = generated(plan, d, civ);
type W = World;
const run = (mutate: (w: W) => void = () => {}, p: Plan = plan) => {
  const w = structuredClone(base.w) as W; mutate(w);
  return extraRules(ctxOf(p, p === plan ? d : derive(p), civ, { w, gen: base.gen })).find(c => c.id === 'SF-22');
};
const SITE = /^street\/(island|foot|crossroads|junction)\//;
const isSite = (c: NonNullable<W['crossings']>[number]) => c.landings.some(l => SITE.test(l.id));
const mid = (c: { line: [V, V] }): V => [(c.line[0][0] + c.line[1][0]) / 2, (c.line[0][1] + c.line[1][1]) / 2];
const kerb = (w: W) => w.crossings!.filter(c => c.kind === 'kerb');

test('the rules the plan states: no plot edge, one tram stop end toward a junction, no stair-foot patch, one island line per road (the left), a footway\'s crossing on its axis, crossroads and junction arms before the node; twins within 30 m of a mouth or 20 m of a bend', () => {
  const r = plan.standards.streetscape.crossings.coverage.rules;
  expect(r).toMatchObject({
    reach: 4, edges: false, stops: { ends: 1, toward: 'junction' }, banks: false, island: { ring: 'crown-circus', per: 'road', side: 'l' }, foot: { kinds: ['mall', 'walk'], at: 'axis' },
    crossroads: { class: ['district'], arm: 'before' }, junction: { class: ['district'], arm: 'before', stopWithin: 30 }, dedupe: { mouth: 30, bend: 20, turn: 45 },
  });
  for (const gone of ['arms', 'mall', 'midBlock']) expect(r, gone).not.toHaveProperty(gone);
});

test('the live export: 26 crossings by rule (stops 10, crossroads 6, foot 4, island 4, junction 1, civic 1), no twins, nothing left out, and SF-22 passes', () => {
  const log = base.w.crossingRules!;
  expect(log.sites).toEqual({ island: 4, foot: 4, crossroads: 6, junction: 1, civic: 1, stops: 10 });
  expect(log.twins).toHaveLength(0);
  expect(log.left).toEqual([]);
  expect(base.w.crossings!).toHaveLength(26);
  expect(base.w.crossings!.filter(c => c.kind === 'stop')).toHaveLength(10);
  expect(base.w.crossings!.filter(c => c.kind === 'bank')).toHaveLength(0);
  expect(kerb(base.w)).toHaveLength(16); // 4 island + 6 crossroads + 1 junction + 3 foot (Garden Walk at Circus Road, Lamplight Lane and Starline Street are the landing pairs there; the Parade's is placed) + the civic block's two
  expect(base.w.crossings!.filter(c => c.landings.some(l => /^street\/island\//.test(l.id)))).toHaveLength(4);
  const r = run()!;
  expect(r.ok, r.detail).toBe(true);
});

test('a footway\'s crossing: the landing pair that stands within 10 m of the axis serves the site (Garden Walk at Circus Road, Lamplight Lane and Starline Street, the last the civic block\'s own); the Parade, with none, is placed', () => {
  const served = base.w.crossingRules!.served!;
  expect(served.map(s => s.split(':')[0]).sort()).toEqual(['foot/garden-walk/circus-road/axis', 'foot/garden-walk/lamplight-lane/axis', 'foot/garden-walk/starline-street/axis']);
  const parade = base.w.crossings!.find(c => c.landings.some(l => /^street\/foot\/crown-parade\/harbour-road\//.test(l.id)))!;
  expect(parade.road).toBe('harbour-road'); expect(Math.abs(mid(parade)[1])).toBeLessThan(15); // on the Parade's axis, or the nearest walk band
});

test('a tram stop has its one crossing at the platform end toward a junction or a footway end; no station bank has one; no plot-edge landing stands that no rule keeps', () => {
  const pts = junctionPoints(ctxOf(plan, d, civ, { w: base.w, gen: base.gen }) as never), near = (p: V) => Math.min(...pts.map(q => dist(p, q)));
  const stops = base.w.crossings!.filter(c => c.kind === 'stop');
  for (const x of stops) {
    const m = base.w.transit.stops.find(s => s.id === x.landings[0]!.edge)!, xs = m.ring.map(p => p[0]), ys = m.ring.map(p => p[1]), c: V = [(Math.min(...xs) + Math.max(...xs)) / 2, (Math.min(...ys) + Math.max(...ys)) / 2], p = mid(x);
    expect(near(p), x.id).toBeLessThanOrEqual(near([2 * c[0] - p[0], 2 * c[1] - p[1]]) + 0.01);
  }
  expect(new Set(stops.map(x => x.id.split('/').slice(0, 4).join('/'))).size).toBe(stops.length); // one per stop
});

test('every landing of a kept crossing stands 3 m past its kerb return\'s tangent point, and past the side of a gate\'s footway table where the tangent point would be (kerbReturn.landings.clear)', () => {
  expect(kerbReturnStd(base.w.crossings ? ctxOf(plan, d, civ, { w: base.w, gen: base.gen }).S : undefined).clear).toBe(3);
  const r = run()!;
  expect(r.ok, r.detail).toBe(true); // clause (e) of SF-22 measures every non-civic landing against every convex return's tangent points and every mouth's table side
  // the failing example: Market Street's crossroads crossing slid 2 m toward the Rocket Gate's mouth stands 1 m from the tangent point
  const x = kerb(base.w).find(c => c.road === 'market-street' && Math.abs(mid(c)[0] + 203) < 1)!;
  const bad = run(w => { const t = w.crossings!.find(c => c.id === x.id)!; for (const l of t.landings) l.at = [l.at[0] + 2, l.at[1]]; })!;
  expect(bad.ok).toBe(false);
  expect(bad.detail).toMatch(/stands [\d.]+ m from the tangent point of .*, kerbReturn\.landings\.clear asks 3/);
});

test('the civic block\'s crossings keep their partner landings (dressing.crossings.at[].partner): x-starline-e pairs with the landing on Lamplight South\'s kerb at its partner kerb point, x-orbit-axis-n with -s', () => {
  const toPlan = toPlanFn(plan.civic), at = (civ.dressing as { crossings: { at: { id: string; at: V; partner: { id?: string; edge?: string; kerb?: V } }[] } }).crossings.at;
  expect(at.map(c => c.id).sort()).toEqual(['x-orbit-axis-n', 'x-orbit-axis-s', 'x-starline-e']); // the six others are dropped (Vantage, civic-block.adjust.json)
  const east = at.find(c => c.id === 'x-starline-e')!, x = base.w.crossings!.find(c => c.landings.some(l => l.id.endsWith('/crossing-x-starline-e')))!;
  const partner = x.landings.find(l => !l.id.endsWith('/crossing-x-starline-e'))!, kerb = toPlan(east.partner.kerb!);
  expect(partner.edge).toBe(east.partner.edge!); // lamplight-south-e/e0
  expect(dist(x.line[x.landings.indexOf(partner)]!, kerb)).toBeLessThan(0.6); // the strip starts on the partner\'s kerb point
  const axis = base.w.crossings!.find(c => c.landings.some(l => l.id.endsWith('/crossing-x-orbit-axis-n')))!;
  expect(axis.landings.map(l => l.id.slice(l.id.lastIndexOf('/crossing-') + 10)).sort()).toEqual(['x-orbit-axis-n', 'x-orbit-axis-s']);
  for (const c of [x, axis]) expect(c.kind).toBe('kerb');
});

test('furniture moved for a site is movable furniture and is no longer in the street; a bench, a bin and a tree are, a lamp post of the civic block is not', () => {
  const ids = new Set(base.w.street.map(s => s.id));
  for (const m of base.w.crossingRules!.moved) { expect(m).toMatch(/^street\/.*\/(tree|lamp|bench|bin|hydrant|phone-booth|mailbox|tub-palm|planter|advertising-column)-\d+$/); expect(ids.has(m), m).toBe(false); }
});

