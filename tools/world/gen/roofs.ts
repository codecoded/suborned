export function generateRoofs(ctx: Ctx, blds: Bld[], terraces: Terrace[]): Roof[] {
  const R = ctx.B.roofs, kit = R.kit, prog = kit.programmes, always = kit.always, out: Roof[] = [], hb = ctx.B.halfBay as number;
  const crowned: { at: V; id: string }[] = [], tip = (ctx.B.towers.crownTip as number) ?? Infinity;
  const zone = zoneOf(ctx), masts: V[] = [];
  for (const b of blds) {
    const id = `${b.id}/roof`, r = rng(id), list = r.shuffle(R.byUse[b.tower ? 'tower' : b.use] as string[]);
    // brief 075: an old-frontage building's long 14 m roof would draw the sign frame on most of the district (90 rooftop boards against the old town's 7): only the
    // remap's 4-storey corner buildings (the old town's boards stood on its taller corners) keep it among their programmes
    if (b.old && b.old.code < 4) { const k = list.indexOf('sign-frame'); if (k >= 0) list.splice(k, 1); }
    const quay = b.ring.c.some(c => kindOf(c) === 'quay');
    const mk = (f: Frame) => {
      const parts: Prim[] = [], P = (n: string, shape: Prim['shape'], surface: string, lu: number, lv: number, size: [number, number, number], base = 0, yawAdd = 0): void => {
        const U: V = [Math.cos(f.yaw), Math.sin(f.yaw)], Vv: V = [-U[1], U[0]];
        parts.push({ id: `${id}/${n}`, shape, surface, c: rv([f.c[0] + U[0] * lu + Vv[0] * lv, f.c[1] + U[1] * lu + Vv[1] * lv]), base: r3(b.z + base), size: [r3(size[0]), r3(size[1]), r3(size[2])], yaw: r4(f.yaw + yawAdd) });
      };
      return { parts, P };
    };
    let chosen = '', frame: Frame | null = null, built: ReturnType<typeof mk> | null = null;
    for (const name of [...list, 'antenna-mast']) {
      const k = prog[name]; if (!k) continue;
      if (name === 'crane-gantry' && !quay) continue;
      if (name === 'observation-saucer' && b.tower === false && b.use !== 'commercial') continue;
      const margin = k.setback === 0 ? 0 : hb, axis = name === 'sawtooth-northlight', f = fit(b.top, margin, axis), [mw, md] = k.minRoof as [number, number];
      const swap = !(f.W >= mw && f.D >= md) && f.W >= md && f.D >= mw;
      if (!((f.W >= mw && f.D >= md) || swap)) continue;
      if (swap) { f.yaw += Math.PI / 2; [f.W, f.D] = [f.D, f.W]; }
      chosen = name; frame = f; built = mk(f); break;
    }
    const f = frame ?? fit(b.top, 0, false), m = built ?? mk(f), { parts, P } = m;
    if (!chosen) chosen = 'antenna-mast';
    // §6 crown: every plot building of >= crownFrom storeys carries a kit crown at the roof's centre (width <= 0.7 x roof, scale 0.8-1.4, tip <= crownTip);
    // within crownNear (150 m) no two crowns share a type, saucers stand >= 400 m apart. Plan tower sites keep their regen order's crown.
    let crown: (KitRef & { at: V }) | undefined;
    if (!b.tower && b.n >= GRAMMAR.crownFrom && prog['antenna-mast'] && !(chosen === 'antenna-mast' && false)) {
      const w0 = Math.min(frame?.W ?? 0, frame?.D ?? 0), cc = frame?.c ?? [0, 0] as V, cr = rng(`${id}/crown`);
      const fits = (CROWN_BY_USE[b.use] ?? CROWN_BY_USE.commercial!).filter(([cid]) => { const a = adoptedBy(cid); return !!a && a.size[0] * a.tags.scale[0] <= 0.7 * w0 && b.z + a.size[1] * a.tags.scale[0] <= tip; });
      const fresh = fits.filter(([cid]) => !crowned.some(o => dist(o.at, cc) < GRAMMAR.crownNear && o.id === cid) && !(cid === 'Crown_Saucer' && crowned.some(o => o.id === cid && dist(o.at, cc) < 400)));
      const opts = fresh.length ? fresh : fits; // every building of crownFrom storeys is crowned; the neighbour rule yields only when all its types are taken nearby
      if (opts.length) {
        const cid = cr.weighted(opts, o => o[1])[0], a = adoptedBy(cid)!, s = Math.min(a.tags.scale[1], (0.7 * w0) / a.size[0], (tip - b.z) / a.size[1]);
        crown = { id: cid, scale: [r3(s), r3(s), r3(s)], yaw: r4(cr.f() * Math.PI * 2), at: rv(cc) }; crowned.push({ at: cc, id: cid });
        chosen = 'antenna-mast'; // the crown stands where the mast would; the programme label keeps SF-15 honest (minRoof 6 x 6)
        const k0 = prog[chosen]; void k0;
      }
    }
    // brief 075 remap: outside the Handover zone an ordinary roof takes the old town's plots (roofline.ts RL-1..RL-4); the zone's roofs, plan tower sites, crowned roofs and the
    // programmes with a form or a board of their own (sign-frame, hover-pad, observation-saucer, the industrial roofs) stay as the plan's programme builds them
    if (!b.tower && !crown && ROOFLINE.has(chosen) && !inRect4(centroid(b.top), zone)) { out.push(oldRoof(ctx, b, id, tip, masts)); continue; }
    const W = f.W, D = f.D, k = prog[chosen];
    // brief 020: a programme's kit piece (tags `roof:<part>`) stands in place of the procedural parts it draws; one piece per roof (Roof.kit), seeded by roof id, none that leaves the roof rect
    const fr = { c: f.c, yaw: f.yaw, W: f.W, D: f.D };
    const piece = (use: string, lu: number, lv: number, ok: (a: KitAsset) => boolean = () => true, first?: string): ReturnType<typeof roofKit> => {
      const cr = rng(`${id}/kit/${use}`), cands = cr.shuffle(forUse(use).filter(ok).sort((a, b) => a.id.localeCompare(b.id)));
      if (first && cr.chance(0.7)) cands.sort((a, b) => Number(b.id === first) - Number(a.id === first)); // the common piece leads on 7 roofs in 10
      for (const a of cands) { const r = roofPiece(a, fr, lu, lv, { maxTop: tip, z: b.z }); if (r) return r; }
      return undefined;
    };
    let padKit: ReturnType<typeof roofKit>, pad = { c: [0, 0] as V, half: [7, 7] as V }; // hover-pad: where it stands in the roof frame, and its half sizes
    switch (chosen) {
      case 'roof-garden': {
        const house = piece('roof:garden-house', 0, -D / 2 + 4.9), shade = house ? undefined : piece('roof:garden-shade', W / 2 - 3.5, 0), bed = house || shade ? undefined : piece('roof:garden-bed', 0, -D / 2 + 1);
        padKit = house ?? shade ?? bed;
        const rows = Math.max(1, Math.floor((D - 4) / 4));
        for (let i = 0; i < rows; i++) if (!house && !(bed && i === 0)) P(`bed-${i}`, 'box', 'park', 0, -D / 2 + 1 + i * ((D - 2) / rows) , [Math.min(W - 2, 12), k.items.bed.w, k.items.bed.h]); // the conservatory takes the beds' place, the planter piece the first bed's
        if (!house && !shade) P('pergola', 'box', 'trim', W / 2 - 3.5, 0, k.items.pergola as [number, number, number]);
        for (let i = 0; i < 3; i++) { P(`tub-${i}`, 'box', 'trim', -W / 2 + 2 + i * 3, D / 2 - 1.5, [1.5, 1.5, 0.9]); P(`palm-${i}`, 'cyl', 'trim', -W / 2 + 2 + i * 3, D / 2 - 1.5, [0.4, 0.4, 4.5], 0.9); P(`crown-${i}`, 'sphere', 'park', -W / 2 + 2 + i * 3, D / 2 - 1.5, [3, 3, 3], 2.4); }
        break; }
      case 'sun-terrace-pool': padKit = piece('roof:pool', 0, 0); if (padKit) break; P('deck', 'box', 'deck', 0, 0, [16, 9, 0.05]); P('pool', 'box', 'water', -1, 0, [12, 5, 0.1], 0.05); P('pergola', 'box', 'trim', 6, 3.6, [6, 3, 3]); P('cabana', 'box', 'awning', -6, -3.6, [3, 3, 2.7]); break;
      case 'hover-pad': { // the kit's SkyPad_Roof (plan programme.kit) stands in the pad's corner of the roof, flush to the parapet band, the kiosk opposite
        const a = adoptedBy(k.kit), [pw, pd] = a ? [a.size[0], a.size[2]] : [14, 14], lu = -W / 2 + pw / 2, lv = a ? -D / 2 + pd / 2 : 0;
        pad = { c: [lu, lv], half: [pw / 2, pd / 2] };
        padKit = a ? roofPiece(a, fr, lu, lv) : undefined; // brief 020: the footprint (SkyPad_Roof's pivot is 2.3 m off its centre) stands flush in the corner, so K-1 holds with pivotOffset counted
        if (!padKit) { pad = { c: [-W / 2 + 7.5, 0], half: [7, 7] }; P('pad', 'cyl', 'trim', -W / 2 + 7.5, 0, [14, 14, 0.6]); }
        P('kiosk', 'box', 'trim', W / 2 - 2.5, D / 2 - 2.5, [3, 3, 3]); break; }
      case 'antenna-mast': { if (crown) break; padKit = piece('roof:antenna-mast', 0, 0, a => Math.min(f.W, f.D) >= (a.id === 'Roof_Mast' ? 6 : 9), 'Roof_Mast'); if (padKit) break; const h = b.tower ? 24 : k.items.mast[2]; P('mast', 'box', 'trim', 0, 0, [2, 2, h]); for (const at of k.items.rings.at as number[]) P(`ring-${at}`, 'cyl', 'trim', 0, 0, [3, 3, 0.3], Math.min(at, h)); break; }
      case 'water-sphere': padKit = piece('roof:water-sphere', 0, 0); if (padKit) break; P('sphere', 'sphere', 'trim', 0, 0, [6, 6, 6], 4); for (let i = 0; i < 4; i++) P(`leg-${i}`, 'box', 'column', i % 2 ? 2 : -2, i < 2 ? 2 : -2, [0.4, 0.4, 4]); break;
      case 'observation-saucer':
        if (b.tower) { P('stem', 'cyl', 'trim', 0, 0, [4, 4, 6]); P('saucer', 'saucer', 'landmark', 0, 0, [16, 16, 4], 6); } else { P('drum', 'cyl', 'trim', 0, 0, [12, 12, 1]); P('dome', 'sphere', 'landmark', 0, 0, [12, 12, 12], 0.5); }
        break;
      case 'sign-frame': { P('leg-0', 'box', 'column', -7, 0, [0.8, 0.8, 2]); P('leg-1', 'box', 'column', 7, 0, [0.8, 0.8, 2]); P('frame', 'box', 'sign', 0, 0, [18, 1, 6], 2); break; }
      case 'tennis-court': padKit = piece('roof:tennis-court', 0, 0); if (padKit) break; P('runoff', 'box', 'deck', 0, 0, [36.6, 18.3, 0.05]); P('court', 'box', 'park', 0, 0, [23.77, 10.97, 0.1], 0.05); P('fence-w', 'box', 'trim', -18.3, 0, [0.1, 18.3, 3.6]); P('fence-e', 'box', 'trim', 18.3, 0, [0.1, 18.3, 3.6]); break;
      case 'sawtooth-northlight': { const n = Math.max(1, Math.floor(D / 6)); for (let i = 0; i < n; i++) P(`tooth-${i}`, 'wedge', 'roof', 0, -D / 2 + 3 + i * 6, [W, 6, 3]); break; }
      case 'barrel-vault': { const span = Math.min(D, 30); P('vault', 'vault', 'roof', 0, 0, [W, span, span / 6]); break; }
      case 'crane-gantry': P('leg-0', 'box', 'trim', 0, -(W + 2) / 2, [1.5, 1.5, 12]); P('leg-1', 'box', 'trim', 0, (W + 2) / 2, [1.5, 1.5, 12]); P('beam', 'box', 'trim', 0, 0, [1.5, W + 2, 1.5], 12); break;
      case 'solar-dish': P('pedestal', 'box', 'column', 0, 0, [2, 2, 4]); P('dish', 'saucer', 'trim', 0, 0, [8, 8, 0.8], 4.2); break;
    }
    // always: plant (one per stair-lift core: one per building), rocket vents on the roof's edge band
    const keep = (x: number, y: number) => chosen !== 'hover-pad' || Math.hypot(Math.max(Math.abs(x - pad.c[0]) - pad.half[0], 0), Math.max(Math.abs(y - pad.c[1]) - pad.half[1], 0)) >= 10; // no vent within 10 m of the pad edge
    // brief 048 (Vela, 2026-10-24; Glyph: 'big flat orange and yellow boxes on the rooftops read as untextured placeholders, the loudest colour in the frame'): the plant and the vents were one box each,
    // the vent in the building's accent enamel at 2 x 2 x 3.5 m. Both are dressed from the same prims, to the plan's sizes (plant 6 x 6 x 3.6, vent 2 x 2 x 3.5, ids keep the SF-15 exemption)
    if (W >= 12 && D >= 8) plant(P, W / 2 - 3, -D / 2 + 3, always.plant.size);
    const nv = Math.max(2, Math.ceil(areaOf(b.top) / 300));
    for (let i = 0; i < nv; i++) { const x = -W / 2 + 1.5 + ((i + 0.5) / nv) * Math.max(0.1, W - 3), y = (i % 2 ? 1 : -1) * Math.max(0, D / 2 - 1.2); if (keep(x, y)) rocketVent(P, `rocket-vent-${i}`, x, y, always['rocket-vent'].size); }
    out.push({ id, building: b.id, programme: chosen, surface: 'roof', z: b.z, c: rv(f.c), size: [r3(f.W), r3(f.D)], yaw: r4(f.yaw), parapet: ACCESSIBLE.has(chosen) ? always.parapet.accessible : always.parapet.other, parts, ...(padKit ? { kit: padKit } : {}), ...(crown ? { crown } : {}) });
  }
  // stepped garden terraces: tubs and a planting strip along each step's roof
  for (const t of terraces) {
    const [x0, x1, y0, y1] = t.rect, w = x1 - x0, parts: Prim[] = [], cy = (y0 + y1) / 2, id = `${t.id}/roof`;
    for (let x = x0 + 3, i = 0; x < x1 - 1; x += 6, i++) {
      parts.push({ id: `${id}/tub-${i}`, shape: 'box', surface: 'trim', c: rv([x, y0 + 1.2]), base: t.z, size: [1.5, 1.5, 0.9], yaw: 0 }, { id: `${id}/palm-${i}`, shape: 'cyl', surface: 'trim', c: rv([x, y0 + 1.2]), base: r3(t.z + 0.9), size: [0.4, 0.4, 3.6], yaw: 0 }, { id: `${id}/crown-${i}`, shape: 'sphere', surface: 'park', c: rv([x, y0 + 1.2]), base: r3(t.z + 2.4), size: [3, 3, 3], yaw: 0 });
    }
    parts.push({ id: `${id}/bed`, shape: 'box', surface: 'park', c: rv([(x0 + x1) / 2, y1 - 1]), base: t.z, size: [r3(w - 2), 1.5, 0.9], yaw: 0 });
    out.push({ id, building: t.id, programme: 'roof-garden', surface: 'roof', z: r3(t.z), c: rv([(x0 + x1) / 2, cy]), size: [r3(w), r3(y1 - y0)], yaw: 0, parapet: ctx.B.roofs.kit.always.parapet.accessible, parts, form: 'terrace' });
  }
  void sub; void ({} as Rect);
  return out;
}

const OFF_STREET = new Set(['none', 'party', 'plot', 'court', 'yard', 'service', 'passage', 'back', '']);
/**
 * Brief 075 remap: an ordinary roof as the old town programmed it (roofline.ts). The roof rect is the building's top inset 0.3 m (DecoKitRoofline.Inset), turned so +v faces
 * the street it fronts. The plan's always-items keep their counts: the plant house and the rocket vents share one plant bay at the end away from a hero corner (6 m per four vents;
 * a roof under 12 x 8 m has no plant house, its vents stand in a 2.6 m strip). The rest of the length splits into plots (RL-1), each with a theme (RL-2) laid from the old items (RL-3);
 * a hero roof (a 4-storey corner of the old frontage) gives its corner plot one slender Roof_Mast, at least MAST_APART from any other (RL-4).
 */
function oldRoof(ctx: Ctx, b: Bld, id: string, tip: number, masts: V[]): Roof {
  const r = rng(`${id}/roofline`), always = ctx.B.roofs.kit.always, f = fit(b.top, 0.3, false);
  const U0: V = [Math.cos(f.yaw), Math.sin(f.yaw)], V0: V = [-U0[1], U0[0]], n = b.ring.p.length;
  // which side the street is on (across: +v), and which end the corner is at (along: the street edge facing along the wall)
  let across = 0, end = 0, ends = 0;
  for (let i = 0; i < n; i++) {
    const c = b.ring.c[i] ?? '', k = kindOf(c); if (OFF_STREET.has(k)) continue;
    const a = b.ring.p[i]!, q = b.ring.p[(i + 1) % n]!, len = dist(a, q), m: V = [(a[0] + q[0]) / 2 - f.c[0], (a[1] + q[1]) / 2 - f.c[1]], dir: V = [(q[0] - a[0]) / (len || 1), (q[1] - a[1]) / (len || 1)];
    const along = Math.abs(dir[0] * U0[0] + dir[1] * U0[1]);
    if (along > 0.7) across += len * Math.sign(m[0] * V0[0] + m[1] * V0[1]);
    else if (along < 0.5) { end += len * Math.sign(m[0] * U0[0] + m[1] * U0[1]); ends += len; }
  }
  if (across < 0) { f.yaw += Math.PI; end = -end; }
  const yaw = f.yaw, W = f.W, D = f.D, U: V = [Math.cos(yaw), Math.sin(yaw)], Vv: V = [-U[1], U[0]];
  const parts: Prim[] = [], kits: (KitRef & { at: V; z: number })[] = [], plots: NonNullable<Roof['plots']> = [];
  const toW = (lu: number, lv: number): V => [f.c[0] + U[0] * lu + Vv[0] * lv, f.c[1] + U[1] * lu + Vv[1] * lv];
  const P: PutPrim = (nm, shape, surface, lu, lv, size, base = 0, yawAdd = 0) => { parts.push({ id: `${id}/${nm}`, shape, surface, c: rv(toW(lu, lv)), base: r3(b.z + base), size: [r3(size[0]), r3(size[1]), r3(size[2])], yaw: r4(yaw + yawAdd) }); };
  const cap = ctx.B.caps?.[b.area] as { m?: number; play?: boolean } | undefined, maxTop = cap?.play && cap.m ? Math.min(cap.m, tip) : tip;
  const fr = { c: f.c, yaw, W, D };
  const asset = (a: string) => adoptedBy(a) ?? (STAND_IN[a] ? adoptedBy(STAND_IN[a]!) : undefined);
  const place = (a: string, lu: number, lv: number, yawDeg: number, lift: number): boolean => {
    const k = asset(a); if (!k) return false;
    const kr = roofPiece(k, fr, lu, lv, { yawAdd: -(yawDeg * Math.PI) / 180, maxTop: maxTop - lift, z: b.z });
    if (!kr) return false;
    kits.push({ ...kr, z: r3(b.z + lift) }); return true;
  };
  const fits = (a: string, lu: number, lv: number, yawDeg: number) => { const k = asset(a); return !!k && !!roofPiece(k, fr, lu, lv, { yawAdd: -(yawDeg * Math.PI) / 180, maxTop, z: b.z }); };
  // the hero corner (RL-4) and the plant bay at the other end
  const hero = !!b.old && b.old.code >= 4 && ends > 0 && Math.abs(across) > 0, cornerEnd = end > 0 ? 1 : end < 0 ? -1 : (r.chance(0.5) ? 1 : -1);
  const plantEnd = hero ? -cornerEnd : (r.chance(0.5) ? 1 : -1), nv = Math.max(2, Math.ceil(areaOf(b.top) / 300)), housed = W >= 12 && D >= 8;
  // vent slots, 3 m apart: in front of the plant house where the roof is deep enough (two columns a bay), else in 2.6 m strips beside it; bays are added until every vent has one
  const front = housed && D >= 10 ? Math.floor((D - 7) / 3) : 0, strip = Math.max(1, Math.floor((D - 0.6) / 3)), slots: V[] = [];
  let bay = housed ? 6 : 0;
  if (front > 0) { for (let k = 0; slots.length < nv; k++) { if (k) bay += 6; for (let j = 0; j < front * 2 && slots.length < nv; j++) slots.push([bay - 6 + 1.5 + (j % 2) * 3, -D / 2 + 6.5 + 1.5 + Math.floor(j / 2) * 3]); } }
  else while (slots.length < nv) { for (let j = 0; j < strip && slots.length < nv; j++) slots.push([bay + 1.3, -D / 2 + 1.5 + j * 3]); bay += 2.6; }
  const u0p = plantEnd > 0 ? W / 2 - bay : -W / 2; // the plant bay spans u0p .. u0p + bay
  if (housed) plant(P, u0p + 3, -D / 2 + 3, always.plant.size);
  slots.forEach(([x, y], i) => rocketVent(P, `rocket-vent-${i}`, u0p + x, y, always['rocket-vent'].size));
  // RL-1 plots over the rest of the length; RL-2 themes; RL-3 items
  const a0 = plantEnd > 0 ? -W / 2 : -W / 2 + bay, a1 = plantEnd > 0 ? W / 2 - bay : W / 2;
  const cs = a1 - a0 >= 5 ? plotCuts(a0, a1, r) : [], themes: Theme[] = [], inset = 0.3;
  let mastAt: V | null = null;
  const heroPlot = hero ? (cornerEnd > 0 ? cs.length - 2 : 0) : -1;
  for (let i = 0; i + 1 < cs.length; i++) {
    const l = cs[i + 1]! - cs[i]! - 2 * inset, am = (cs[i]! + cs[i + 1]!) / 2;
    const leads = (t: Theme) => { const it = t.fill(l, D, rng(`${id}/lead/${t.name}`))[0]; return !it || fits(it.a, am + it.u, it.v, it.yaw ?? 0); };
    let th: Theme | null = null;
    if (i === heroPlot && l >= MAST.minL && D >= MAST.minD) {
      const c = toW(am, 0);
      if (!masts.some(m => dist(m, c) < MAST_APART) && leads(MAST)) { th = MAST; mastAt = c; }
    }
    themes.push(th ?? pickTheme(l, D, i > 0 ? themes[i - 1]! : null, r, leads));
  }
  for (let i = 0; i < themes.length; i++) {
    const th = themes[i]!, am = (cs[i]! + cs[i + 1]!) / 2, l = cs[i + 1]! - cs[i]! - 2 * inset, pid = `${id}/plot-${i}`;
    plots.push({ id: pid, theme: th.name, c: rv(toW(am, 0)), size: [r3(l), r3(D)], yaw: r4(yaw) });
    if (th.deck) { // one deck along neighbouring decked plots, set in from the roof's ends and from bare plots (DecoKitRoofline.Programme)
      const x0 = cs[i]! + (i === 0 || !themes[i - 1]!.deck ? inset : 0), x1 = cs[i + 1]! - (i === themes.length - 1 || !themes[i + 1]!.deck ? inset : 0);
      P(`plot-${i}-deck`, 'box', 'deck', (x0 + x1) / 2, 0, [x1 - x0, D, 0.05]);
    }
    const lift = th.deck ? 0.05 : 0, lu = l / 2 - 1.4, lv = D / 2 - 1.4;
    if (th.lawn && lu > 0 && lv > 0) {
      P(`plot-${i}-kerb`, 'box', 'roof', am, 0, [2 * lu + 0.4, 2 * lv + 0.4, 0.08], lift);
      P(`plot-${i}-lawn`, 'box', 'park', am, 0, [2 * lu, 2 * lv, 0.1], lift);
    }
    for (const it of th.fill(l, D, rng(`${pid}/${th.name}`))) {
      const onLawn = th.lawn && Math.abs(it.u) < lu && Math.abs(it.v) < lv;
      // nothing stands on the plant house or the vents
      const k = asset(it.a); if (!k) continue;
      const half = Math.max(k.size[0], k.size[2]) / 2, x = am + it.u;
      if (x + half > u0p - 0.2 && x - half < u0p + bay + 0.2) continue;
      place(it.a, x, it.v, it.yaw ?? 0, lift + (onLawn ? 0.1 : 0));
    }
  }
  if (mastAt && kits.some(k => k.id === 'Roof_Mast')) masts.push(mastAt);
  const accessible = themes.some(t => t.accessible);
  return { id, building: b.id, programme: 'roofline', surface: 'roof', z: b.z, c: rv(f.c), size: [r3(W), r3(D)], yaw: r4(yaw), parapet: accessible ? always.parapet.accessible : always.parapet.other, parts, plots, kits };
}
