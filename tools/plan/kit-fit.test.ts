// K-1: the generated world passes; a kit piece too big for its slot, a gateway foot on a pylon, and a tower tip over the ceiling each fail.
// K-2: the placed tower pieces stand to the tips their orders state; a height cut the pieces were not regenerated for fails, naming the sites.
import { expect, setDefaultTimeout, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { civic } from './civic';
import { derive, type Plan } from './plan';
import { worldOf } from '../world/build';
import { kitFitChecks } from './kit-fit';
import { TIP_TOL, ctxOf } from './world-ctx';

setDefaultTimeout(120000);
const root = resolve(import.meta.dir, '../..'), read = (p: string) => JSON.parse(readFileSync(resolve(root, p), 'utf8'));
const plan: Plan = read('contracts/world/harbour-district.plan.json'), d = derive(plan), civ = civic(plan.civic, read(plan.civic.block));
const { world, gen } = worldOf(plan, d, civ), v = { w: world, gen }, all = (p: Plan = plan, x = v) => kitFitChecks(ctxOf(p, d, civ, x));
const run = (p: Plan = plan, x = v) => all(p, x)[0]!;
// brief 075 remap: the old town's plan has no tower sites and no pier tower, so K-2 and the pier gateway's failing example run on the pinned plan from before the remap
// (briefs/075/remap/base.plan.json, committed), generated by today's code
const pre: Plan = read('briefs/075/remap/base.plan.json'), preD = derive(pre), preCiv = civic(pre.civic, read(pre.civic.block));
let preV: { w: ReturnType<typeof worldOf>['world']; gen: ReturnType<typeof worldOf>['gen'] } | undefined;
const pv = () => (preV ??= (({ world: w, gen: g }) => ({ w, gen: g }))(worldOf(pre, preD, preCiv)));
const preAll = (p: Plan = pre, x = pv()) => kitFitChecks(ctxOf(p, preD, preCiv, x)), preRun = (p: Plan = pre, x = pv()) => preAll(p, x)[0]!;
const k2 = (p: Plan = pre, x = pv()) => preAll(p, x).find(c => c.id === 'K-2')!;
// the Crown Avenue arch as the plan places it (landmarks.disc-west.gateway), cloned so its failing examples can move its feet
const arch: Plan = structuredClone(plan);
const archD = derive(arch);
let archV: typeof preV;
const av = () => (archV ??= (({ world: w, gen: g }) => ({ w, gen: g }))(worldOf(arch, archD, civ)));
const archRun = (p: Plan = arch, x = av()) => kitFitChecks(ctxOf(p, archD, civ, x))[0]!;
/** A clone of the pre-remap plan with the named tower sites' stated tips moved by `by` metres (the world, and so the placed pieces, stay as built). */
const tips = (by: Record<string, number>): Plan => {
  const p: Plan = structuredClone(pre);
  for (const s of p.standards.buildings.towers.sites as { id: string; regen: { tip: number } }[]) if (s.id in by) s.regen.tip += by[s.id]!;
  return p;
};

test('K-1 passes on the plan', () => { const k = run(); expect(k.id).toBe('K-1'); expect(k.ok).toBe(true); });

test('K-1 fails a landmark piece scaled past its disc, a gateway on the beam and a tower tip over crownTip', () => {
  const w = structuredClone(v.w); w.landmarks.find(l => l.id === 'landmark/sphere')!.kit!.scale = [0.6, 0.6, 0.6];
  expect(run(plan, { ...v, w }).detail).toContain('landmark/sphere');
  const p: Plan = structuredClone(pre), g = (p.megastructures!.find(m => m.id === 'skyport-tower') as any).gateway; // the pier tower: pre-remap
  g.feet[0] = [479.1, 485.9, 0.5, 7];
  expect(preRun(p).detail).toContain('gateway/foot-0');
  const q: Plan = structuredClone(pre); q.standards.buildings.towers.crownTip = 70; // the tower sites: pre-remap
  expect(preRun(q).detail).toContain('tip 75');
});

test('K-1 checks a landmark gateway: the Crown Avenue arch is emitted, its feet in the frontage zone up to the building line; a foot on the walk, out of the piece, against a lamp or with no building line behind the pavement fails', () => {
  const lm = av().w.landmarks.find(l => l.id === 'landmark/disc-west')!, gw = (arch.landmarks.find(l => l.id === 'disc-west') as any).gateway, [y0, y1] = [gw.feet[0][2], gw.feet[0][3]];
  expect(lm.gateway).toMatchObject({ id: 'ParabolicArch@crown-avenue', scale: [1, 1, 1], yaw: 0, at: gw.c });
  expect(archRun().ok).toBe(true); // feet x 14-17: past Crown Avenue's 6.5 m access pavement (to x 16.5), inside the 1.5 m paved setback to the old wall at x 18 (the runs' building line)
  const bare: Plan = structuredClone(arch); (bare as any).blocks = (bare as any).blocks.map((b: any) => ({ ...b, runs: b.runs.filter((r: any) => r.faces !== 'access:crown-avenue') }));
  expect(archRun(bare).detail).toContain('disc-west/gateway/foot-0: not in its zone (frontage)'); // no run fronts the avenue: the pavement ends at 16.5
  const walk: Plan = structuredClone(arch); (walk.landmarks.find(l => l.id === 'disc-west') as any).gateway.feet[0] = [-13, -10, y0, y1]; // x 10-13 = the walk zone (dk 0-3: the kerb and walk zones)
  const k = archRun(walk).detail!;
  expect(k).toContain('disc-west/gateway/foot-0: not in its zone (frontage)'); expect(k).toContain("crown-avenue's walk zone");
  const out: Plan = structuredClone(arch); (out.landmarks.find(l => l.id === 'disc-west') as any).gateway.feet[1] = [16, 19, y0, y1]; // past the piece's x 17
  expect(archRun(out).detail).toContain('disc-west/gateway/foot-1: outside the piece');
  const w = structuredClone(av().w), lamp = structuredClone(w.street.find(s => s.kind === 'lamp')!); lamp.id = 'street/test/lamp'; lamp.at = [12.8, gw.c[1]]; lamp.z = 0.18; w.street.push(lamp); // 1.2 m off the east plinth (x 14)
  expect(archRun(arch, { ...av(), w }).detail).toContain('disc-west/gateway/foot-1: street/test/lamp (lamp) within 1.5 m of the plinth');
  const gone = structuredClone(av().w); delete gone.landmarks.find(l => l.id === 'landmark/disc-west')!.gateway;
  expect(archRun(arch, { ...av(), w: gone }).detail).toContain('disc-west: gateway ParabolicArch@crown-avenue not emitted');
});

test('K-2 passes on the pre-remap plan: every placed tower piece stands to its order\'s tip', () => {
  const k = k2();
  expect(k.ok).toBe(true); expect(k.detail).toBeUndefined();
  expect(Number(k.value.split('/')[1])).toBeGreaterThan(0); // it judged placed pieces, not an empty list
});

test('K-2 fails the heights-cut variant: the needle and both avenue gates, and nothing else', () => {
  // out/plan/variants/heights-cut.plan.json: avenue-needle 30 -> 26 storeys (tip -14.4), the avenue gates 33 -> 30 (-10.8); the pieces are fixed-size, so the world is unchanged
  const k = k2(tips({ 'avenue-needle': -14.4, 'avenue-gate-w': -10.8 }));
  expect(k.ok).toBe(false);
  expect(k.detail).toContain('3 fail');
  expect(k.detail).toMatch(/avenue-needle: Tower_Needle@avenue-needle built to [\d.]+ m, regen.tip [\d.]+ \(\+14\.\d m\)/);
  expect(k.detail).toMatch(/avenue-gate-w: DiscTower@avenue-gate-w .*\(\+10\.\d m\)/);
  expect(k.detail).toMatch(/avenue-gate-e: DiscTower@avenue-gate-e .*its pair avenue-gate-w's regen\.tip/); // the matched partner takes the tip of its pair
  expect(k.detail).not.toContain('crescent-terrace');
  expect(preRun(tips({ 'avenue-needle': -14.4 })).ok).toBe(true); // K-1 (the ceiling) is not what caught it
});

test('K-2 holds the piece to the tolerance either way, and does not judge a site whose piece is not adopted', () => {
  expect(k2(tips({ 'avenue-needle': TIP_TOL - 0.1 })).ok).toBe(true);
  expect(k2(tips({ 'avenue-needle': TIP_TOL + 0.1 })).ok).toBe(false);
  expect(k2(tips({ 'avenue-needle': -(TIP_TOL + 0.1) })).ok).toBe(false); // a piece shorter than its order is as wrong as a taller one
  const w = structuredClone(pv().w), i = w.signatures.findIndex(s => s.id === 'tower/avenue-needle');
  w.signatures[i] = { id: 'tower/avenue-needle', kind: 'tower', source: 'procedural', base: w.signatures[i]!.base, tip: 0, pending: 'Tower_Needle@avenue-needle' };
  expect(k2(tips({ 'avenue-needle': -14.4 }), { ...pv(), w }).ok).toBe(true); // pending: the procedural tower stands, nothing built to hold against the order
});
